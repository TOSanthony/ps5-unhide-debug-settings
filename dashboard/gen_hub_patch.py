#!/usr/bin/env python3
# Regenerates hub_patch_files.h from ../nidus-widgets/hub-signin-patch/{config.json,widget.js}
# Run this after editing either source file, then rebuild dashboard.elf.
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC_DIR = os.path.join(HERE, "..", "nidus-widgets", "hub-signin-patch")
OUT = os.path.join(HERE, "hub_patch_files.h")

def c_string(path):
    with open(path, "r", encoding="utf-8") as f:
        lines = f.read().split("\n")
    out = []
    for line in lines:
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append('    "%s\\n"' % esc)
    return "\n".join(out)

config_c = c_string(os.path.join(SRC_DIR, "config.json"))
widget_c = c_string(os.path.join(SRC_DIR, "widget.js"))

with open(OUT, "w", encoding="utf-8") as f:
    f.write("/* Auto-generated by gen_hub_patch.py -- do not edit by hand. */\n")
    f.write("static const char HUB_PATCH_CONFIG_JSON[] =\n%s;\n\n" % config_c)
    f.write("static const char HUB_PATCH_WIDGET_JS[] =\n%s;\n" % widget_c)

print("wrote", OUT)
