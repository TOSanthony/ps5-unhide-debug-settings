#!/usr/bin/env python3
# Regenerates orbit_latest_files.h from
# ../nidus-widgets/orbit-latest/{config.json,widget.js,orbit.png}
# Run this after editing any of the three source files, then rebuild dashboard.elf.
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC_DIR = os.path.join(HERE, "..", "nidus-widgets", "orbit-latest")
OUT = os.path.join(HERE, "orbit_latest_files.h")

def c_string(path):
    with open(path, "r", encoding="utf-8") as f:
        lines = f.read().split("\n")
    out = []
    for line in lines:
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append('    "%s\\n"' % esc)
    return "\n".join(out)

def c_bytes(path):
    with open(path, "rb") as f:
        data = f.read()
    out = []
    for i in range(0, len(data), 20):
        chunk = data[i:i + 20]
        out.append("    " + ",".join(str(b) for b in chunk) + ",")
    return len(data), "\n".join(out)

config_c = c_string(os.path.join(SRC_DIR, "config.json"))
widget_c = c_string(os.path.join(SRC_DIR, "widget.js"))
glyph_len, glyph_c = c_bytes(os.path.join(SRC_DIR, "orbit.png"))

with open(OUT, "w", encoding="utf-8") as f:
    f.write("/* Auto-generated by gen_orbit_latest.py -- do not edit by hand. */\n")
    f.write("static const char ORBIT_LATEST_CONFIG_JSON[] =\n%s;\n\n" % config_c)
    f.write("static const char ORBIT_LATEST_WIDGET_JS[] =\n%s;\n\n" % widget_c)
    f.write("static const unsigned char ORBIT_LATEST_GLYPH_PNG[] = {\n%s\n};\n" % glyph_c)
    f.write("static const unsigned int ORBIT_LATEST_GLYPH_PNG_LEN = %d;\n" % glyph_len)

print("wrote", OUT)
