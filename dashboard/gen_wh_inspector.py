#!/usr/bin/env python3
# Regenerates wh_inspector_files.h from ../nidus-widgets/wh-inspector/{config.json,widget.js}
# Run this after editing either source file, then rebuild dashboard.elf.
# Temporary diagnostic widget (see Ghostpad/virtual-controller investigation) -- remove
# this script and its generated header once that investigation is done.
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC_DIR = os.path.join(HERE, "..", "nidus-widgets", "wh-inspector")
OUT = os.path.join(HERE, "wh_inspector_files.h")

def c_string(path):
    with open(path, "r", encoding="utf-8") as f:
        lines = f.read().split("\n")
    out = []
    for line in lines:
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append('    "%s\\n"' % esc)
    return "\n".join(out)

config_c = c_string(os.path.join(SRC_DIR, "config.json"))
widget_c = c_string(os.path.join(SRC_DIR, "widget.js"))

with open(OUT, "w", encoding="utf-8") as f:
    f.write("/* Auto-generated by gen_wh_inspector.py -- do not edit by hand. */\n")
    f.write("static const char WH_INSPECTOR_CONFIG_JSON[] =\n%s;\n\n" % config_c)
    f.write("static const char WH_INSPECTOR_WIDGET_JS[] =\n%s;\n" % widget_c)

print("wrote", OUT)
